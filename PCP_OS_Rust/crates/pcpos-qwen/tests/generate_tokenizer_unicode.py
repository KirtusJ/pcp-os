"""Generate only the L/N/White_Space tables used by the pinned Qwen2 profile.
Usage: python generate_tokenizer_unicode.py PINNED_UNICODE_DATA_CPP OUTPUT_RS
The complete input is identified by its SHA-256, not the host Python Unicode version.
"""
import hashlib,pathlib,re,sys
source=pathlib.Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(source).hexdigest()=='5c80b44db0958e673a1940e2a602a5eea2725916ff67bbaeb48ecc7634f84f29','not the pinned Unicode input'
text=source.decode()
block=text.split('unicode_ranges_flags = {',1)[1].split('};',1)[0]
ranges=[(int(a,16),int(b,16)&6) for a,b in re.findall(r'\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}',block)]
assert ranges[0][0]==0 and ranges[-1][0]==0x110000
small=[]
for start,kind in ranges:
    if not small or small[-1][1]!=kind:small.append((start,kind))
white=text.split('unicode_set_whitespace = {',1)[1].split('};',1)[0]
whites=[int(n,16) for n in re.findall(r'0x([0-9A-Fa-f]+)',white)]
assert len(whites)==25
lower=text.split('unicode_map_lowercase = {',1)[1].split('};',1)[0]
for a,b in re.findall(r'\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}',lower):
    if chr(int(b,16)) in 'strev mld'.replace(' ',''): assert int(a,16)<128
out='// Generated by tests/generate_tokenizer_unicode.py; no host Unicode dependency.\n'
out+='// llama.cpp a956a852c9c8bc1fb07206364838ddef299178c0/src/unicode-data.cpp\n'
out+='// Input SHA-256: '+hashlib.sha256(source).hexdigest()+'\n'
out+='// Upstream MIT license: see THIRD_PARTY_NOTICES.\n'
out+='const RANGES: &[(u32,u8)] = &[\n'
out+=''.join(f'    (0x{start:06x},{kind}),\n' for start,kind in small)+'];\n'
out+='pub(super) fn category(c:char)->u8 {\n    let i=RANGES.partition_point(|r|r.0<=c as u32); RANGES[i-1].1\n}\n'
out+='pub(super) fn whitespace(c:char)->bool {\n    matches!(c as u32, '+ '|'.join(hex(n) for n in whites)+')\n}\n'
pathlib.Path(sys.argv[2]).write_text(out,encoding='utf-8',newline='\n')
print({'input_sha256':hashlib.sha256(source).hexdigest(),'ranges':len(small),'output_sha256':hashlib.sha256(out.encode()).hexdigest()})
