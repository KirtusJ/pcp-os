#!/usr/bin/env python3
"""Write src/font.rs: the printable ASCII characters as 10 by 20 cells of coverage (0 = none, 255 = full),
rasterised once from DejaVu Sans Mono at 16 pixels. The kernel build does not run this; its output is kept
in the source. DejaVu Sans Mono is distributed under the Bitstream Vera licence, which permits copying,
merging and distribution of the font and of what is made from it, provided its notices are kept: see NOTICE.md.

    python3 tools/make_font.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf src/font.rs
    python3 tools/make_font.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf src/font-2x.bin --double
"""
import sys
from PIL import Image, ImageDraw, ImageFont
W, H, SIZE = 10, 20, 16
if sys.argv[3:] == ["--double"]:
    font = ImageFont.truetype(sys.argv[1], SIZE * 2)
    with open(sys.argv[2], "wb") as output:
        for code in range(32, 127):
            im = Image.new("L", (W * 2, H * 2), 0)
            ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=255)
            output.write(im.tobytes())
    sys.exit(0)
font = ImageFont.truetype(sys.argv[1], SIZE)
out = ["//! The kernel's one typeface: printable ASCII as 10 by 20 cells of coverage. Generated by tools/make_font.py from",
       "//! DejaVu Sans Mono (Bitstream Vera licence; see NOTICE.md). Not edited by hand.", "",
       "pub const CELL_WIDTH: usize = %d;" % W, "pub const CELL_HEIGHT: usize = %d;" % H, "pub const FIRST: u8 = 32;", "",
       "pub static GLYPHS: [[u8; %d]; 95] = [" % (W * H)]
for code in range(32, 127):
    im = Image.new("L", (W, H), 0)
    ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=255)
    px = list(im.tobytes())
    out.append("    [" + ", ".join(str(v) for v in px) + "],")
out.append("];")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
